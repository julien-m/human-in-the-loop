import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { Store } from '../src/store.mjs';
import { handleHook } from '../src/hook.mjs';

test('real stdio protocol: tools, hidden UI token, scope validation and resource', { timeout: 10000 }, async t => {
  const dir = mkdtempSync(join(tmpdir(), 'human-loop-stdio-'));
  const store = new Store(join(dir, 'state.sqlite')), scope = store.begin('protocol-thread', 'protocol-project').scope;
  store.close();
  const client = new Client({ name: 'human-loop-tests', version: '1' }, { capabilities: {} });
  t.after(async () => { await client.close(); rmSync(dir, { recursive: true, force: true }); });
  await client.connect(new StdioClientTransport({ command: process.execPath, args: ['dist/server.mjs'], cwd: process.cwd(), env: { PATH: process.env.PATH || '', HUMAN_LOOP_DATA_DIR: dir }, stderr: 'pipe' }));
  const tools = (await client.listTools()).tools;
  assert.equal(tools.length, 9);
  assert.deepEqual(tools.find(t => t.name === 'human_respond')._meta.ui.visibility, ['app']);
  const empty = await client.callTool({ name: 'my_tasks', arguments: {} });
  assert.equal(empty.structuredContent.identityRequired, true);
  const created = await client.callTool({ name: 'assign_task', arguments: { scope, actionId: 'protocol-create', title: 'Pick a name', why: 'A public fixture', kind: 'answer' } });
  assert(!created.isError);
  const token = created._meta.uiToken;
  assert(token);
  assert(!JSON.stringify(created.structuredContent).includes(token));
  const denied = await client.callTool({ name: 'human_read', arguments: { scope, uiToken: scope } });
  assert.equal(denied.structuredContent.error, 'invalid_ui_token');
  const task = created.structuredContent.task;
  const saved = await client.callTool({ name: 'human_respond', arguments: { scope, uiToken: token, taskId: task.id, actionId: 'protocol-response', expectedRevision: 0, action: 'answer', text: 'The chosen name' } });
  assert(!saved.isError);
  const read = await client.callTool({ name: 'list_tasks', arguments: { scope } });
  assert.equal(read.structuredContent.pending.length, 1);
  await client.callTool({ name: 'acknowledge_responses', arguments: { scope, responseIds: [saved.structuredContent.response.id] } });
  assert.equal((await client.callTool({ name: 'list_tasks', arguments: { scope } })).structuredContent.pending.length, 0);
  const resource = await client.readResource({ uri: 'ui://human-in-the-loop/0.1.0/tasks.html' });
  assert(resource.contents[0].text.includes('<main id="app">'));
});

test('hooks restore exact scope after compaction, track turns and avoid Stop loops', { timeout: 2000 }, t => {
  const dir = mkdtempSync(join(tmpdir(), 'human-loop-hooks-')), store = new Store(join(dir, 'state.sqlite'));
  t.after(() => { store.close(); rmSync(dir, { recursive: true, force: true }); });
  const event = { hook_event_name: 'SessionStart', session_id: 'hook-thread', cwd: dir };
  const first = handleHook(store, event).hookSpecificOutput.additionalContext;
  const scope = first.match(/scope=([^ .]+)/)[1];
  assert(first.includes('assign_task'));
  const task = store.assign(scope, { title: 'Check manually', why: 'Fixture only', actionId: 'hook-create' }).task;
  handleHook(store, { ...event, hook_event_name: 'UserPromptSubmit' });
  assert.equal(store.snapshot(scope).working, true);
  const compacted = handleHook(store, { ...event, source: 'compact' });
  assert(compacted.hookSpecificOutput.additionalContext.includes(`scope=${scope}`));
  assert(store.snapshot(scope).working);
  store.respond(scope, { taskId: task.id, expectedRevision: 0, action: 'done', actionId: 'hook-done' });
  const stop = { ...event, hook_event_name: 'Stop' };
  assert.equal(handleHook(store, stop).decision, 'block');
  assert.deepEqual(handleHook(store, { ...stop, stop_hook_active: true }), {});
  assert.equal(store.snapshot(scope).working, false);
  assert.deepEqual(handleHook(store, { ...event, session_id: '' }), {});
  assert.deepEqual(handleHook(store, { ...event, agent_id: 'subagent' }), {});
  const config = JSON.parse(readFileSync('hooks/hooks.json', 'utf8'));
  assert(config.hooks.SessionStart && config.hooks.Stop && config.hooks.SessionEnd);
});
